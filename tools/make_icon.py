"""Juggle Coach icon (design `appIcon`): one set of shapes drawn three ways, so they always match: the adaptive-icon
foreground vector (`res/drawable/ic_launcher_foreground.xml`), the legacy launcher PNG and the 512 export for the
factory gallery.

    python tools/make_icon.py <export-512.png>

Lake teal tile #1A8A98; two white dashed throw arcs crossing into an "X" arch (left up / right down and mirrored, six
dashes each), a small peak ring above the crossing, and three solid scarf flakes (narrow top, wide bottom): orange
#FF7A59 where the left arc lands, blue #6FBFFF where the right one lands, yellow #FFD24A at the top. No text, no
gradient. Coordinates are the vector's 108-unit viewport (safe zone 21..87).
"""
import math
import os
import sys

from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
LAKE = (0x1A, 0x8A, 0x98, 255)
WHITE = (255, 255, 255, 255)
CORAL = (0xFF, 0x7A, 0x59, 255)
SKY = (0x6F, 0xBF, 0xFF, 255)
LEMON = (0xFF, 0xD2, 0x4A, 255)

STROKE = 3.4
RING = (54, 25, 4.0, 2.6)  # cx, cy, r, stroke


def bez(p0, p1, p2, n=80):
    return [((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0], (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1]) for t in (i / n for i in range(n + 1))]


# each arc rises from one hand and peaks over the other shoulder (cascade), so the two cross in the middle
ARCS = [bez((30, 84), (80, 12), (80, 64)), bez((78, 84), (28, 12), (28, 64))]


def dashes(pts, count=6):
    # 2*count-1 equal slices of the arc length; the even ones are dashes
    acc = [0.0]
    for a, b in zip(pts, pts[1:]):
        acc.append(acc[-1] + math.dist(a, b))
    total = acc[-1]
    slices = 2 * count - 1
    out = []
    for k in range(0, slices, 2):
        s0, s1 = total * k / slices, total * (k + 1) / slices
        out.append([p for p, s in zip(pts, acc) if s0 <= s <= s1])
    return out


def flake(cx, top, h, w):
    """Scarf flake: a point at the top, widening to a soft, slightly wavy bottom."""
    pts = []
    for i in range(13):
        v = i / 12
        half = w / 2 * math.sin(v * math.pi * 0.62) ** 0.9
        pts.append((cx + half, top + v * h))
    bottom = [(cx + w / 2 * (1 - 2 * j / 6), top + h + (1.4 if j % 2 else 0)) for j in range(7)]
    left = [(2 * cx - x, y) for x, y in reversed(pts)]
    return pts + bottom[1:-1] + left


FLAKES = [(CORAL, flake(28, 67, 13, 10)), (SKY, flake(80, 67, 13, 10)), (LEMON, flake(54, 32, 10, 8))]


def vector():
    def fmt(v):
        return f"{v:.2f}".rstrip("0").rstrip(".")

    out = [
        '<?xml version="1.0" encoding="utf-8"?>\n',
        "<!-- Juggle Coach: two white dashed crossing throw arcs, a peak ring, orange / blue / yellow scarf flakes "
        "(design appIcon); generated by tools/make_icon.py -->\n",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n',
    ]
    for arc in ARCS:
        for d in dashes(arc):
            path = "M" + "L".join(f"{fmt(x)},{fmt(y)}" for x, y in d[::3] + [d[-1]])
            out.append(
                f'    <path\n        android:pathData="{path}"\n        android:strokeColor="#FFFFFFFF"\n'
                f'        android:strokeWidth="{STROKE}"\n        android:strokeLineCap="round"\n'
                '        android:strokeLineJoin="round"\n        android:fillColor="#00000000" />\n'
            )
    cx, cy, r, w = RING
    out.append(
        f'    <path\n        android:pathData="M{cx - r},{cy}a{r},{r} 0,1 1,{2 * r},0a{r},{r} 0,1 1,{-2 * r},0z"\n'
        f'        android:strokeColor="#FFFFFFFF"\n        android:strokeWidth="{w}"\n        android:fillColor="#00000000" />\n'
    )
    for color, pts in FLAKES:
        hexc = "#FF%02X%02X%02X" % color[:3]
        path = "M" + "L".join(f"{fmt(x)},{fmt(y)}" for x, y in pts) + "Z"
        out.append(f'    <path\n        android:pathData="{path}"\n        android:fillColor="{hexc}" />\n')
    out.append("</vector>\n")
    return "".join(out)


def raster(size, rounded):
    k = 8
    S = size * k
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if rounded:
        d.rounded_rectangle([0, 0, S - 1, S - 1], radius=int(S * 0.22), fill=LAKE)
    else:
        d.rectangle([0, 0, S, S], fill=LAKE)
    u = S / 108.0
    for arc in ARCS:
        for seg in dashes(arc):
            d.line([(x * u, y * u) for x, y in seg], fill=WHITE, width=int(STROKE * u), joint="curve")
            for x, y in (seg[0], seg[-1]):
                rr = STROKE * u / 2
                d.ellipse([x * u - rr, y * u - rr, x * u + rr, y * u + rr], fill=WHITE)
    cx, cy, r, w = RING
    d.ellipse([(cx - r - w / 2) * u, (cy - r - w / 2) * u, (cx + r + w / 2) * u, (cy + r + w / 2) * u], outline=WHITE, width=int(w * u))
    for color, pts in FLAKES:
        d.polygon([(x * u, y * u) for x, y in pts], fill=color)
    return img.resize((size, size), Image.LANCZOS)


def main():
    with open(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), "w", encoding="utf-8") as f:
        f.write(vector())
    raster(192, rounded=False).save(os.path.join(RES, "mipmap-xxxhdpi", "ic_launcher.png"))
    if len(sys.argv) > 1:
        raster(512, rounded=True).save(sys.argv[1])
        print("wrote", sys.argv[1])


if __name__ == "__main__":
    main()
